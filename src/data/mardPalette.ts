// Generate the 221 MARD BeadColor objects with verified: true flag
export const MARD_PALETTE: BeadColor[] = MARD_SERIES_DEFINITIONS.flatMap((series) =>
  series.colors.map((c) => {
    const rgb = hexToRgb(c.hex);
    const lab = rgbToLab(rgb[0], rgb[1], rgb[2]);
    return {
      id: `mard_${c.code.toLowerCase()}`,
      name: c.name,
      code: c.code,
      hex: c.hex,
      brand: 'mard' as const,
      category: series.category,
      series: `${series.name} (${series.nameZh})`,
      verified: true, // Verified community reference data
      rgb,
      lab,
    };
  })
);
