export interface PixelBitmap {
  width: number;
  height: number;
  data: boolean[][]; // [y][x] true = filled bead pixel
}

export function renderTextToPixelBitmap(
  text: string,
  fontStyle: PixelFontStyle = 'classic_5x7',
  letterSpacing: number = 1
): PixelBitmap {
  const upper = text.toUpperCase();
  if (!upper || upper.length === 0) {
    return { width: 0, height: 0, data: [] };
  }

  const isMini = fontStyle === 'mini_3x5';
  const isBold = fontStyle === 'bold_7x9';
  const charH = isMini ? 5 : 7;
  const fontDict = isMini ? FONT_3X5 : FONT_5X7;

  // Measure total width
  let totalWidth = 0;
  const charBitmaps: boolean[][][] = [];

  for (let i = 0; i < upper.length; i++) {
    const ch = upper[i];
    const glyphCols = fontDict[ch] || fontDict['?'] || [0x00, 0x00, 0x00, 0x00, 0x00];
    const glyphWidth = glyphCols.length;

    // Create 2D grid for this character [y][x]
    const grid: boolean[][] = [];
    for (let y = 0; y < charH; y++) {
      const row: boolean[] = [];
      for (let x = 0; x < glyphWidth; x++) {
        const colVal = glyphCols[x];
        const isSet = (colVal & (1 << y)) !== 0;
        row.push(isSet);
      }
      grid.push(row);
    }

    // If bold 7x9 style: double the pixel width and height
    if (isBold) {
      const boldGrid: boolean[][] = [];
      for (let y = 0; y < charH + 1; y++) {
        const row: boolean[] = [];
        for (let x = 0; x < glyphWidth + 1; x++) {
          const original = (grid[y]?.[x]) || false;
          const right = (grid[y]?.[x - 1]) || false;
          row.push(original || right);
        }
        boldGrid.push(row);
      }
      charBitmaps.push(boldGrid);
      totalWidth += glyphWidth + 1 + (i < upper.length - 1 ? letterSpacing : 0);
    } else {
      charBitmaps.push(grid);
      totalWidth += glyphWidth + (i < upper.length - 1 ? letterSpacing : 0);
    }
  }

  const finalH = isBold ? charH + 1 : charH;
  const fullData: boolean[][] = Array.from({ length: finalH }, () =>
    Array(totalWidth).fill(false)
  );

  let currentX = 0;
  for (let c = 0; c < charBitmaps.length; c++) {
    const bmp = charBitmaps[c];
    const bW = bmp[0].length;
    const bH = bmp.length;

    for (let y = 0; y < bH; y++) {
      for (let x = 0; x < bW; x++) {
        if (bmp[y][x]) {
          fullData[y][currentX + x] = true;
        }
      }
    }
    currentX += bW + letterSpacing;
  }

  return {
    width: totalWidth,
    height: finalH,
    data: fullData,
  };
}
